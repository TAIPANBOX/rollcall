//go:build ignore

// mksysnum writes zsysnum_linux_<goarch>.go for every GOARCH a rollcall package ships: the name
// of every system call golang.org/x/sys/unix knows for that GOARCH, mapped to the unix.SYS_*
// constant itself, so the numbers come from x/sys when the loader is compiled for that GOARCH.
// The name is the constant's, lower-cased and without SYS_, which is the kernel's __NR_ name
// (SYS__LLSEEK is _llseek, SYS_NEWFSTATAT is newfstatat), the name procd's seccomp profiles use.
//
//	cd tools/seccomp-run && go run mksysnum.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// arches maps each GOARCH to the AUDIT_ARCH constant the kernel puts in seccomp_data.arch.
var arches = map[string]string{
	"amd64":  "AUDIT_ARCH_X86_64",
	"arm64":  "AUDIT_ARCH_AARCH64",
	"arm":    "AUDIT_ARCH_ARM",
	"mips":   "AUDIT_ARCH_MIPS",
	"mipsle": "AUDIT_ARCH_MIPSEL",
}

var sysConst = regexp.MustCompile(`(?m)^\s*(SYS_[A-Z0-9_]+)\s*=\s*[0-9]+\s*$`)

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}} {{.Version}}", "golang.org/x/sys").Output()
	if err != nil {
		log.Fatalf("locate golang.org/x/sys: %v", err)
	}
	dir, version, _ := strings.Cut(strings.TrimSpace(string(out)), " ")
	goarches := make([]string, 0, len(arches))
	for a := range arches {
		goarches = append(goarches, a)
	}
	sort.Strings(goarches)
	for _, goarch := range goarches {
		src := filepath.Join(dir, "unix", "zsysnum_linux_"+goarch+".go")
		data, err := os.ReadFile(src)
		if err != nil {
			log.Fatal(err)
		}
		consts := sysConst.FindAllSubmatch(data, -1)
		if len(consts) == 0 {
			log.Fatalf("%s: no SYS_ constants", src)
		}
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by mksysnum.go from golang.org/x/sys %s unix/zsysnum_linux_%s.go; DO NOT EDIT.\n\n", version, goarch)
		fmt.Fprintf(&b, "//go:build linux && %s\n\npackage main\n\nimport \"golang.org/x/sys/unix\"\n\n", goarch)
		fmt.Fprintf(&b, "// auditArch is seccomp_data.arch for a %s process.\nconst auditArch = unix.%s\n\n", goarch, arches[goarch])
		fmt.Fprintf(&b, "// sysnums maps the kernel's name of every %s system call to its number.\nvar sysnums = map[string]uint32{\n", goarch)
		seen := map[string]bool{}
		for _, m := range consts {
			c := string(m[1])
			name := strings.ToLower(strings.TrimPrefix(c, "SYS_"))
			if seen[name] {
				continue
			}
			seen[name] = true
			fmt.Fprintf(&b, "\t%q: unix.%s,\n", name, c)
		}
		b.WriteString("}\n")
		formatted, err := format.Source(b.Bytes())
		if err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile("zsysnum_linux_"+goarch+".go", formatted, 0o644); err != nil {
			log.Fatal(err)
		}
	}
}

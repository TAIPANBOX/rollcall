//go:build linux && (amd64 || arm64 || arm || mips || mipsle)

// Command seccomp-run installs a rollcall seccomp profile as a real kernel filter and then runs a
// program under it, the way procd's ujail runs rollcalld on a router: no_new_privs, then a
// filter that kills the whole process on any system call the profile does not list, then execve
// of the program in the same process, so the program's PID is this one's.
//
//	seccomp-run -profile rollcall.json [-without name,...] -- rollcalld -config ...
//	seccomp-run -name 157       print the name of system call 157 on this architecture
//	seccomp-run -arch           print this architecture (a check that this binary runs here)
//
// The system call numbers come from golang.org/x/sys/unix for the GOARCH it is built for
// (zsysnum_linux_*.go, generated by mksysnum.go). A name the architecture does not have is an
// error. -without drops names from the profile, so CI can prove a missing call is caught.
// Test-only: nothing under cmd/ or internal/ imports it, and no release builds it.
package main

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"runtime"
	"strings"
	"unsafe"

	"golang.org/x/sys/unix"
)

func main() {
	profilePath := flag.String("profile", "", "procd seccomp profile (packaging/seccomp/generate.sh output)")
	without := flag.String("without", "", "comma-separated names to leave out of the profile")
	name := flag.Int("name", -1, "print the name of this system call number and exit")
	arch := flag.Bool("arch", false, "print the architecture and exit")
	flag.Parse()
	switch {
	case *arch:
		fmt.Printf("%s audit arch %#x, %d system calls known\n", runtime.GOARCH, uint32(auditArch), len(sysnums))
		return
	case *name >= 0:
		for n, nr := range sysnums {
			if int(nr) == *name {
				fmt.Println(n)
				return
			}
		}
		fmt.Printf("unknown(%d)\n", *name)
		return
	}
	if err := run(*profilePath, *without, flag.Args()); err != nil {
		fmt.Fprintln(os.Stderr, "seccomp-run:", err)
		os.Exit(2)
	}
}

func run(profilePath, without string, args []string) error {
	if profilePath == "" || len(args) == 0 {
		return fmt.Errorf("usage: seccomp-run -profile <file> [-without name,...] -- <program> [args]")
	}
	data, err := os.ReadFile(profilePath)
	if err != nil {
		return err
	}
	names, err := readProfile(data)
	if err != nil {
		return err
	}
	drop := map[string]bool{}
	for _, n := range strings.Split(without, ",") {
		if n = strings.TrimSpace(n); n != "" {
			drop[n] = true
		}
	}
	nrs, err := numbers(names, sysnums, drop)
	if err != nil {
		return err
	}
	prog, err := buildFilter(auditArch, nrs)
	if err != nil {
		return err
	}
	path, err := exec.LookPath(args[0])
	if err != nil {
		return err
	}
	argv0, err := unix.BytePtrFromString(path)
	if err != nil {
		return err
	}
	argv, err := cStrings(args)
	if err != nil {
		return err
	}
	envv, err := cStrings(os.Environ())
	if err != nil {
		return err
	}
	filter := make([]unix.SockFilter, len(prog))
	for i, in := range prog {
		filter[i] = unix.SockFilter{Code: in.code, Jt: in.jt, Jf: in.jf, K: in.k}
	}
	fprog := unix.SockFprog{Len: uint16(len(filter)), Filter: &filter[0]}

	// The filter applies to the calling thread and is inherited across execve, which keeps only
	// that thread. Locking the goroutine to it keeps the install and the execve on one thread; the
	// other threads stay unfiltered until execve ends them, so nothing of this loader runs under
	// the profile except the execve itself.
	runtime.LockOSThread()
	if err := unix.Prctl(unix.PR_SET_NO_NEW_PRIVS, 1, 0, 0, 0); err != nil {
		return fmt.Errorf("no_new_privs: %w", err)
	}
	if err := unix.Prctl(unix.PR_SET_SECCOMP, unix.SECCOMP_MODE_FILTER, uintptr(unsafe.Pointer(&fprog)), 0, 0); err != nil {
		return fmt.Errorf("install the filter: %w", err)
	}
	_, _, errno := unix.RawSyscall(unix.SYS_EXECVE, uintptr(unsafe.Pointer(argv0)),
		uintptr(unsafe.Pointer(&argv[0])), uintptr(unsafe.Pointer(&envv[0])))
	return fmt.Errorf("execve %s: %w (%d calls allowed)", path, errno, len(nrs))
}

// cStrings is the NULL-terminated array of C strings execve takes.
func cStrings(ss []string) ([]*byte, error) {
	out := make([]*byte, len(ss)+1)
	for i, s := range ss {
		p, err := unix.BytePtrFromString(s)
		if err != nil {
			return nil, err
		}
		out[i] = p
	}
	return out, nil
}
